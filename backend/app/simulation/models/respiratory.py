class SingleCompartmentLung(SimulationModel):
    definition = DEFINITION

    def simulate(self, params: dict[str, float], dt: float = DT) -> SimulationResult:
        period = 60.0 / params["resp_rate"]
        t_i = params["insp_fraction"] * period
        p_max, c, r = params["muscle_pressure"], params["compliance"], params["resistance"]
        breaths = int(params["breaths"])

        def deriv(t: float, v: float) -> float:
            return (muscle_pressure(t, period, t_i, p_max) - v / c) / r

        t, v = rk4_scalar(deriv, 0.0, 0.0, breaths * period, dt)
        p_mus = np.array([muscle_pressure(ti, period, t_i, p_max) for ti in t])
        flow = (p_mus - v / c) / r

        last = t >= (breaths - 1) * period - 1e-9
        v_last, f_last = v[last], flow[last]
        tidal = float(v_last.max() - v_last.min())

        warnings = []
        if r * c > (period - t_i) / 3:
            warnings.append(
                "Expiration is shorter than about three time constants (R·C), so the lungs "
                "do not empty back to FRC: gas is trapped."
            )

        shown = min(2, breaths)
        window = t >= (breaths - shown) * period - 1e-9
        stride = max(1, int(round(DISPLAY_SAMPLE / dt)))
        idx = np.flatnonzero(window)[::stride]
        t0 = t[idx[0]]

        def rounded(a: np.ndarray, nd: int = 4) -> list[float]:
            return [round(float(x), nd) for x in a]

        return SimulationResult(
            time=rounded(t[idx] - t0),
            series={
                "lung_volume": rounded(params["frc"] + v[idx]),
                "airflow": rounded(flow[idx]),
                "muscle_pressure": rounded(p_mus[idx], 3),
                "alveolar_pressure": rounded(-r * flow[idx], 3),
            },
            metrics={
                "tidal_volume": round(1000 * tidal, 1),
                "minute_ventilation": round(tidal * params["resp_rate"], 2),
                "peak_inspiratory_flow": round(float(f_last.max()), 3),
                "peak_expiratory_flow": round(float(-f_last.min()), 3),
                "time_constant": round(r * c, 3),
                "trapped_volume": round(1000 * float(v_last[-1]), 1),
            },
            warnings=warnings,
        )
