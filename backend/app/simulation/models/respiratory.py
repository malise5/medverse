"""Single-compartment model of quiet breathing (equation of motion of the respiratory system).

    R · dV/dt + V / C = P_mus(t)

V is lung volume above functional residual capacity (FRC), R the total respiratory
resistance, C the total respiratory-system compliance and P_mus the pressure generated by
the inspiratory muscles, prescribed as a half-sine during inspiration and zero during
(passive) expiration. Airway-opening pressure is atmospheric. See Bates (2009), ch. 2.
"""

